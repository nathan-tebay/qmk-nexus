import { useKeyboardStore } from '@/store/keyboard'
import { useKeyboardSync } from '@/store/useKeyboardSync'
import { MetadataForm } from './MetadataForm'
import FeatureToggles from './FeatureToggles'
import { BuildPanel } from './BuildPanel'
import { BuildInstructionsPanel } from './BuildInstructionsPanel'
import { FEATURE_MODULES } from './modules'
import { validateMatrices } from '@/utils/validateMatrices'
import { validateKeyboardConfig } from '@/utils/validateKeyboardConfig'
import styles from './BuildStage.module.css'

import { featureSettingsOk } from '@/utils/validateFeatureConfig'

export default function BuildStage() {
  const config = useKeyboardStore((s) => s.config)
  const setConfig = useKeyboardStore((s) => s.setConfig)
  const { save } = useKeyboardSync()

  function handleMetaChange(field: string, value: string) {
    setConfig({ [field]: value })
  }

  const enabledFeatures = Object.entries(config.features)
    .filter(([, on]) => on)
    .map(([id]) => FEATURE_MODULES.find((m) => m.id === id)?.name ?? id)
  const matrixValidation = validateMatrices(config)
  const configOk = validateKeyboardConfig(config).length === 0
  const featuresOk = featureSettingsOk(config)
  const sourceModeLabel = config.sourceMode === 'qmk_native' ? 'QMK Native' : 'Generated Source'

  return (
    <div className={styles.stage}>

      {/* ── Top bar ── */}
      <div className={styles.topBar}>
       <div className={styles.topCard}>

        <div className={styles.metadataSection}>
          <div className={styles.sectionTitle}>Keyboard Metadata</div>
          <MetadataForm
            name={config.name}
            manufacturer={config.manufacturer}
            mcu={config.mcu}
            usbVid={config.usbVid}
            usbPid={config.usbPid}
            onChange={handleMetaChange}
          />
          <BuildInstructionsPanel
            config={config}
            enabledFeatures={enabledFeatures}
            keyboardId={config.id}
            onSaveFirst={save}
          />
        </div>

        <div className={styles.buildSection}>
          <div className={styles.buildHeader}>
            <div className={styles.sectionTitle}>Build Firmware</div>
            <span
              className={styles.sourceBadge}
              title={config.sourceMode === 'qmk_native'
                ? 'Build uses the upstream QMK keyboard and a generated Nexus keymap overlay'
                : 'Build uses QMK source files generated by QMK Nexus'}
            >
              {sourceModeLabel}
            </span>
          </div>
          <div className={styles.buildDisclaimer}>
            Not all keyboards or configuration options have been tested. Please use the Report Build Issue button if you run into issues building or flashing your keyboard.
          </div>
          <div className={styles.healthRow} aria-label="Keyboard build readiness">
            <HealthPill ok={config.keys.length > 0} label="Layout" />
            <HealthPill ok={matrixValidation.matrixOk && matrixValidation.ledOk} label="Pins" />
            <HealthPill ok={featuresOk} label="Features" />
            <HealthPill ok={configOk && matrixValidation.matrixOk && matrixValidation.ledOk && featuresOk} label="Build Ready" />
          </div>

          <div className={styles.summary}>
            <div className={styles.summaryRow}>
              <span className={styles.summaryLabel}>Keyboard</span>
              <span className={styles.summaryValue}>{config.name || '(unnamed)'}</span>
            </div>
            <div className={styles.summaryRow}>
              <span className={styles.summaryLabel}>MCU</span>
              <span className={styles.summaryValue}>{config.mcu}</span>
            </div>
            <div className={styles.summaryRow}>
              <span className={styles.summaryLabel}>Keys</span>
              <span className={styles.summaryValue}>{config.keys.length}</span>
            </div>
            <div className={styles.summaryRow}>
              <span className={styles.summaryLabel}>Layers</span>
              <span className={styles.summaryValue}>{config.layers.length}</span>
            </div>
            {enabledFeatures.length > 0 && (
              <div className={styles.summaryRow}>
                <span className={styles.summaryLabel}>Features</span>
                <span className={styles.summaryValue}>{enabledFeatures.join(', ')}</span>
              </div>
            )}
          </div>

          <BuildPanel keyboardId={config.id} onSaveFirst={save} />
        </div>
       </div>
      </div>

      {/* ── Feature Modules ── */}
      <div className={styles.featuresSection}>
        <div className={styles.featuresSectionTitle}>Feature Modules</div>
        <FeatureToggles />
      </div>
    </div>
  )
}

function HealthPill({ ok, label }: { ok: boolean; label: string }) {
  return (
    <span className={`${styles.healthPill} ${ok ? styles.healthOk : styles.healthWarn}`}>
      {ok ? '✓' : '!'} {label}
    </span>
  )
}
